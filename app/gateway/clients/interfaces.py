from __future__ import annotations

from datetime import date
from decimal import Decimal
from typing import Protocol


class MasterDataClient(Protocol):
    def list_products(self, group_id=None, active=None, search=None, sort_by="CODE", sort_direction="ASC"): ...
    def get_product(self, product_id: str): ...
    def resolve_external_mapping(self, source_system: str, entity_type: str, external_code: str, internal_id: str): ...


class ProductionClient(Protocol):
    def list_import_runs(self, source=None, period: date | None = None): ...
    def get_import_run(self, run_id: str): ...
    def start_import(self, source: str, period: date): ...
    def retry_import(self, run_id: str): ...
    def get_cost_data(self, product_id: str, period: date): ...


class FinancialClient(Protocol):
    def list_import_runs(self, source=None, period: date | None = None): ...
    def get_import_run(self, run_id: str): ...
    def start_import(self, source: str, period: date): ...
    def retry_import(self, run_id: str): ...
    def get_overhead_amount(self, period: date) -> Decimal: ...
    def get_sales_data(self, product_id: str, period: date): ...


class CostingClient(Protocol):
    def get_cost_breakdown(self, product_id: str, period: date, version: int | None = None): ...
    def calculate_costs(self, period: date, items, overhead_amount: Decimal, allocation_base: str): ...


class AnalyticsClient(Protocol):
    def list_profitability(
        self,
        product_ids: list[str] | None,
        period_from: date,
        period_to: date,
        min_margin_percent: Decimal | None = None,
        sort_by: str = "PERIOD",
        sort_direction: str = "ASC",
    ): ...
    def aggregate_profitability(self, product_ids, period_from, period_to, min_margin_percent=None): ...
    def calculate_profitability(self, period: date, items): ...
    def get_calculation_status(self, job_id: str): ...


class ReportingClient(Protocol):
    def get_report_export(self, export_id: str): ...
    def create_export(self, format: str, requested_by: str, report_id: str | None = None): ...
